import fs from "node:fs";
import path from "node:path";
import process from "node:process";

const repoRoot = process.cwd();
const sourceRoot = path.join(repoRoot, "src", "content", "studio");
const outputPath = path.join(sourceRoot, "generated.ts");
const changelogPath = path.join(repoRoot, "CHANGELOG.md");
const studioLogFile = "迭代手记.md";

function toPosix(relativePath) {
	return relativePath.split(path.sep).join("/");
}

function comparePaths(left, right) {
	const leftParts = left.split("/");
	const rightParts = right.split("/");
	const length = Math.min(leftParts.length, rightParts.length);
	for (let index = 0; index < length; index += 1) {
		const leftPart = leftParts[index];
		const rightPart = rightParts[index];
		const leftAscii = /^[\x00-\x7F]/.test(leftPart);
		const rightAscii = /^[\x00-\x7F]/.test(rightPart);
		if (leftAscii !== rightAscii) {
			return leftAscii ? -1 : 1;
		}
		const compared = leftPart.localeCompare(rightPart, "zh-CN");
		if (compared !== 0) {
			return compared;
		}
	}
	return leftParts.length - rightParts.length;
}

function normalizeLineEndings(value) {
	return value.replace(/^\uFEFF/, "").replace(/\r\n?/g, "\n");
}

function buildStudioChangelog(raw) {
	const normalized = normalizeLineEndings(raw).trim();
	if (!normalized) {
		return "# 迭代手记 · Changelog\n";
	}
	const lines = normalized.split("\n");
	const headingIndex = lines.findIndex((line) => /^#\s+/.test(line.trim()));
	if (headingIndex === -1) {
		return `# 迭代手记 · Changelog\n\n${normalized}\n`;
	}
	lines[headingIndex] = "# 迭代手记 · Changelog";
	return `${lines.join("\n").trim()}\n`;
}

function collectStudioSnapshot(rootDir) {
	const entries = [];

	function walk(currentDir) {
		const relativeDir = toPosix(path.relative(rootDir, currentDir));
		if (relativeDir) {
			entries.push({
				kind: "directory",
				relativePath: relativeDir,
			});
		}

		const dirEntries = fs.readdirSync(currentDir, { withFileTypes: true })
			.sort((left, right) => left.name.localeCompare(right.name, "en"));
		for (const entry of dirEntries) {
			if (entry.name === "generated.ts" || entry.name === ".keep") {
				continue;
			}
			const absolutePath = path.join(currentDir, entry.name);
			if (entry.isDirectory()) {
				walk(absolutePath);
				continue;
			}
			if (entry.isFile() && entry.name.endsWith(".md")) {
				entries.push({
					kind: "file",
					relativePath: toPosix(path.relative(rootDir, absolutePath)),
					content: fs.readFileSync(absolutePath, "utf8"),
				});
			}
		}
	}

	walk(rootDir);
	entries.push({
		kind: "file",
		relativePath: studioLogFile,
		content: buildStudioChangelog(fs.readFileSync(changelogPath, "utf8")),
	});
	return entries.sort((left, right) => comparePaths(left.relativePath, right.relativePath));
}

const studioSnapshot = collectStudioSnapshot(sourceRoot);

const header = [
	"// This file is generated by scripts/generate-studio-content.mjs",
	"// Do not edit it by hand. Edit the markdown files under src/content/studio instead.",
	"",
	"export interface StudioDirectoryEntry {",
	'\treadonly kind: "directory";',
	"\treadonly relativePath: string;",
	"}",
	"",
	"export interface StudioFileEntry {",
	'\treadonly kind: "file";',
	"\treadonly relativePath: string;",
	"\treadonly content: string;",
	"}",
	"",
	"export type StudioSnapshotEntry = StudioDirectoryEntry | StudioFileEntry;",
	"",
].join("\n");

const entries = studioSnapshot.map((entry) => {
	if (entry.kind === "directory") {
		return `\t{\n\t\tkind: "directory",\n\t\trelativePath: ${JSON.stringify(entry.relativePath)},\n\t}`;
	}
	return `\t{\n\t\tkind: "file",\n\t\trelativePath: ${JSON.stringify(entry.relativePath)},\n\t\tcontent: ${JSON.stringify(entry.content)},\n\t}`;
}).join(",\n");

const body = `export const STUDIO_CONTENT_SNAPSHOT: readonly StudioSnapshotEntry[] = [\n${entries}\n];\n`;

fs.writeFileSync(outputPath, `${header}${body}`, "utf8");

import fs from "node:fs";
import path from "node:path";
import process from "node:process";

const repoRoot = process.cwd();
const builtinRoot = path.join(repoRoot, "src", "skills", "packs", "builtin");
const outputPath = path.join(builtinRoot, "markdown.ts");

const markdownSources = [
	["BUILTIN_COMPILE_WIKI_MARKDOWN", path.join(builtinRoot, "compile-wiki", "SKILL.md")],
	["BUILTIN_LOOKUP_WIKI_MARKDOWN", path.join(builtinRoot, "lookup-wiki", "SKILL.md")],
	["BUILTIN_RESOLVE_CONFLICT_MARKDOWN", path.join(builtinRoot, "resolve-conflict", "SKILL.md")],
	["BUILTIN_OBSIDIAN_CLI_MARKDOWN", path.join(builtinRoot, "obsidian-cli", "SKILL.md")],
	["BUILTIN_OBSIDIAN_MARKDOWN_MARKDOWN", path.join(builtinRoot, "obsidian-markdown", "SKILL.md")],
	["BUILTIN_JSON_CANVAS_MARKDOWN", path.join(builtinRoot, "json-canvas", "SKILL.md")],
	["BUILTIN_OBSIDIAN_BASES_MARKDOWN", path.join(builtinRoot, "obsidian-bases", "SKILL.md")],
];

const header = [
	"// This file is generated by scripts/generate-builtin-skill-markdown.mjs",
	"// Do not edit it by hand. Edit the per-skill SKILL.md source files instead.",
	"",
].join("\n");

const body = markdownSources.map(([constName, filePath]) => {
	const markdown = fs.readFileSync(filePath, "utf8");
	return `export const ${constName} = ${JSON.stringify(markdown)};`;
}).join("\n\n");

fs.writeFileSync(outputPath, `${header}${body}\n`, "utf8");
